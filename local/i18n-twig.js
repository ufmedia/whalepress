/**
 * Extract translatable strings from Twig templates into a PHP file that
 * `wp i18n make-pot` can scan (WP-CLI doesn't parse Twig). Run via `npm run i18n`.
 *
 * Supports __(), _x() and _n() calls with literal arguments and the theme's
 * text domain, e.g. {{ __('Skip to content', 'whalepress') }}.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { readEnv, root, success } from './lib.js';

const theme = readEnv().THEME_NAME || 'whalepress';
const themeDir = path.join(root, 'wp-content', 'themes', theme);
const output = path.join(themeDir, 'languages', 'twig-strings.php');

const str = `(?:'((?:[^'\\\\]|\\\\.)*)'|"((?:[^"\\\\]|\\\\.)*)")`;
const domain = `\\s*,\\s*['"]${theme}['"]\\s*\\)`;
const patterns = [
	new RegExp(`\\b(__)\\(\\s*${str}${domain}`, 'g'),
	new RegExp(`\\b(_x)\\(\\s*${str}\\s*,\\s*${str}${domain}`, 'g'),
	new RegExp(`\\b(_n)\\(\\s*${str}\\s*,\\s*${str}\\s*,\\s*[^,]+${domain}`, 'g'),
];

const files = readdirSync(path.join(themeDir, 'templates'), { recursive: true })
	.filter((file) => file.endsWith('.twig'))
	.sort();

const php = (value) => `'${value.replace(/\\(?!')/g, '\\\\').replace(/(?<!\\)'/g, "\\'")}'`;
const lines = [];

for (const file of files) {
	const source = readFileSync(path.join(themeDir, 'templates', file), 'utf8');
	for (const pattern of patterns) {
		for (const match of source.matchAll(pattern)) {
			const [fn, ...groups] = match.slice(1);
			const args = [];
			for (let i = 0; i < groups.length; i += 2) {
				args.push(php(groups[i] ?? groups[i + 1]));
			}
			const line = source.slice(0, match.index).split('\n').length;
			const call =
				fn === '_n'
					? `_n( ${args[0]}, ${args[1]}, 1, '${theme}' )`
					: `${fn}( ${args.join(', ')}, '${theme}' )`;
			lines.push(`// templates/${file}:${line}\n${call};`);
		}
	}
}

writeFileSync(
	output,
	`<?php\n// Generated by local/i18n-twig.js from the Twig templates. Do not edit; never loaded.\n// phpcs:ignoreFile\nreturn;\n\n${lines.join('\n')}\n`,
);
success(`Extracted ${lines.length} strings from ${files.length} Twig templates`);
